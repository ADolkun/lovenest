#!/usr/bin/env bash
# Install an optional native hook, or a legacy companion for an existing prek hook.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
require_main_checkout
action=${1:-status}
[[ "$#" -le 2 ]] || die 'Usage: tools/deploy/install-pull-hook.sh [enable [branch]|disable|status]'
hooks=$(git -C "$ROOT" rev-parse --path-format=absolute --git-common-dir)/hooks
hook="$hooks/post-merge"
legacy="$hook.legacy"
marker='lovenest-managed-pull-hook-v1'
case "$action" in
  status)
    enabled=$(git -C "$ROOT" config --local --bool --get lovenest.deployOnPull || printf false)
    note "Pull deployment configured: $enabled"
    note "Branch: $(git -C "$ROOT" config --local --get lovenest.deployBranch || printf lovenest)"
    note "Checkout: $(git -C "$ROOT" config --local --get lovenest.deployRoot || printf 'not configured')"
    configured_root=$(git -C "$ROOT" config --local --get lovenest.deployRoot || true)
    if git -C "$ROOT" config --get core.hooksPath >/dev/null; then
      note 'Dispatcher: core.hooksPath is configured; check manual integration (docs/self-hosting.md).'
      [[ "$enabled" != true ]] || exit 1
    elif [[ "$enabled" == true && "$configured_root" != "$ROOT" ]]; then
      note 'Dispatcher: checkout path changed; rerun tools/deploy/install-pull-hook.sh enable.'
      exit 1
    elif [[ -x "$hook" ]] && grep -Fq "$marker" "$hook"; then
      note 'Dispatcher: installed (native Git hook).'
    elif [[ -x "$hook" && -x "$legacy" ]] && grep -Fq '# File generated by prek:' "$hook" && grep -Fq "$marker" "$legacy"; then
      note 'Dispatcher: installed (prek legacy chain).'
    else
      note 'Dispatcher: missing or unmanaged; run tools/deploy/install-pull-hook.sh enable, or check manual integration.'
      [[ "$enabled" != true ]] || exit 1
    fi
    exit 0 ;;
  disable)
    git -C "$ROOT" config --local lovenest.deployOnPull false
    note 'Pull deployment disabled. Other hooks were preserved.'
    exit 0 ;;
  enable) ;;
  *) die 'Usage: tools/deploy/install-pull-hook.sh [enable [branch]|disable|status]' ;;
esac
branch=${2:-lovenest}
git check-ref-format "refs/heads/$branch" >/dev/null || die 'Invalid deployment branch.'
if git -C "$ROOT" config --get core.hooksPath >/dev/null; then
  die 'core.hooksPath is configured (including an empty value). Existing hooks were preserved; see docs/self-hosting.md for manual integration.'
fi
mkdir -p "$hooks"
[[ ! -L "$hook" && ! -L "$legacy" ]] || die 'A post-merge hook is a symlink. It was preserved; see docs/self-hosting.md for manual integration.'
target="$hook"
if [[ -e "$hook" ]]; then
  if grep -Fq "$marker" "$hook"; then
    [[ ! -e "$legacy" ]] || die 'An additional legacy hook exists. Both hooks were preserved; integrate manually.'
  elif grep -Fq '# File generated by prek:' "$hook"; then
    target="$legacy"
    [[ ! -e "$legacy" ]] || grep -Fq "$marker" "$legacy" \
      || die 'A custom legacy hook already exists. It was preserved; see docs/self-hosting.md for manual integration.'
  else
    die 'A custom post-merge hook already exists. It was preserved; see docs/self-hosting.md for manual integration.'
  fi
elif [[ -e "$legacy" ]]; then
  die 'A legacy hook already exists without its dispatcher. It was preserved; integrate manually.'
fi
temporary=$(mktemp "$hooks/lovenest-hook.XXXXXX")
trap 'rm -f "$temporary"' EXIT
cat > "$temporary" <<'HOOK'
#!/usr/bin/env bash
# lovenest-managed-pull-hook-v1 — live deployment, independent of indexing tools.
# Normal prek install preserves this as post-merge.legacy; do not use --force.
set -euo pipefail
case ",${SKIP:-}," in *,deploy-lovenest,*) exit 0 ;; esac
[[ "$(git config --local --bool --get lovenest.deployOnPull 2>/dev/null || true)" == true ]] || exit 0
root=$(git config --local --get lovenest.deployRoot) || exit 0
[[ "$(git rev-parse --show-toplevel)" == "$root" ]] || exit 0
branch=$(git symbolic-ref --quiet --short HEAD) || exit 0
[[ "$branch" == "$(git config --local --get lovenest.deployBranch)" ]] || exit 0
if [[ ! -x "$root/tools/deploy/post-merge.sh" ]]; then
  printf 'lovenest: deployment tooling is missing. Restore tools/deploy or disable with git config --local lovenest.deployOnPull false.\n' >&2
  exit 1
fi
exec "$root/tools/deploy/post-merge.sh" "$@"
HOOK
chmod 755 "$temporary"
mv "$temporary" "$target"
trap - EXIT
git -C "$ROOT" config --local lovenest.deployRoot "$ROOT"
git -C "$ROOT" config --local lovenest.deployBranch "$branch"
git -C "$ROOT" config --local lovenest.deployOnPull true
note "Pull deployment enabled for $branch in $ROOT. No deployment was started."
note 'Use SKIP=deploy-lovenest git pull to skip once, or install-pull-hook.sh disable to disable.'
